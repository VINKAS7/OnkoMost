"""Structured handover (fields from Handover_obsah.docx) assembled from the patient graph.

Every value carries its sources (document, date, quote, verified?). A doctor confirms or edits each field;
the coordinator can add what is missing. Nothing here is generated by the LLM – it only arranges facts.
"""
