def _fmt_date(d) -> str:
    return f"{d.day}. {d.month}. {d.year}" if d else ""


def _src(sources: list[dict]) -> list[dict]:
    return [{"doc_id": s["doc_id"], "title": s["title"], "date": s["doc_date"], "facility": s.get("facility"),
             "quote": s.get("quote", ""), "match": s.get("match"), "method": s.get("method")} for s in sources]


def _verified(sources: list[dict]) -> bool:
    return any(s.get("match") for s in sources)


def _merge_contained(conditions: list[dict]) -> list[dict]:
    """Two letters may word one condition differently ('depresivní ladění' vs 'v r. 2019 … depresivní ladění'):
    keep the more detailed wording and pool the sources."""
    out: list[dict] = []
    for c in sorted(conditions, key=lambda c: -len(c["props"].get("name", ""))):
        f = fold(c["props"].get("name", ""))
        host = next((o for o in out if f and f in fold(o["props"].get("name", ""))), None)
        if host:
            host["sources"] = host["sources"] + c["sources"]
            host["props"].setdefault("icd10", c["props"].get("icd10"))
        else:
            out.append({**c, "props": dict(c["props"])})
    return sorted(out, key=lambda c: min((s["doc_date"] or date.min) for s in c["sources"]) if c["sources"] else date.min)


def build(patient_uuid: str, cutoff: date, entries: list[dict] | None = None, referring_doctor: dict | None = None) -> dict:
    facts = graph.facts(patient_uuid, cutoff)
    patient = graph.patient(patient_uuid)
    entries = entries or []
    fields: list[dict] = []

    def field(key, section, label, items, required=True, note=""):
        fields.append({"key": key, "section": section, "label": label, "items": items, "required": required, "note": note})

    def item(text, sources=None, **extra):
        sources = sources or []
        return {"text": text, "sources": _src(sources), "verified": _verified(sources) if sources else True, **extra}

    psrc = [{"doc_id": None, "title": "Hlavička dokumentů", "doc_date": None, "quote": patient.get("patient_name", ""),
             "match": "exact", "method": "rule"}]
    name = patient.get("patient_name", "")
    first, _, last = name.partition(" ")
    field("first_name", "patient", "Jméno", [item(first, psrc)] if first else [])
    field("last_name", "patient", "Příjmení", [item(last, psrc)] if last else [])
    dob = patient.get("dob")
    if dob is not None and hasattr(dob, "to_native"):
        dob = dob.to_native()
    field("age", "patient", "Věk", [item(f"{age_on(dob, cutoff)} let (nar. {_fmt_date(dob)})", psrc)] if dob else [])
    field("sex", "patient", "Pohlaví", [item(SEX.get(patient.get("sex", ""), ""), psrc)] if patient.get("sex") else [])
    field("insurer", "patient", "Zdravotní pojišťovna", [item(patient["insurer"], psrc)] if patient.get("insurer") else [])
    field("rc", "patient", "Rodné číslo", [item(patient["rc"], psrc)] if patient.get("rc") else [], required=False)
    field("address", "patient", "Adresa", [item(patient["address"], psrc)] if patient.get("address") else [], required=False)

    field("patient_phone", "contacts", "Kontakt na pacienta (telefon)",
          [item(patient["phone"], psrc)] if patient.get("phone") else [])
    field("patient_email", "contacts", "E-mail pacienta", [], required=False, note="Požadováno formulářem MDT")
    cps = facts.get("contact_person", [])
    field("contact_person", "contacts", "Kontaktní osoba + telefon",
          [item(f"{c['props'].get('name')} ({c['props'].get('relation') or 'vztah neuveden'}), tel. {c['props'].get('phone') or '—'}",
                c["sources"]) for c in cps])
    rd = (facts.get("referring_doctor") or [None])[0]
    if rd or referring_doctor:
        p = rd["props"] if rd else referring_doctor
        field("referring_doctor", "contacts", "Referující lékař",
              [item(f"{p.get('name')}, {p.get('practice', '')}, {p.get('address', '')}, tel. {p.get('phone') or '—'}",
                    rd["sources"] if rd else [])], required=False)
    field("referring_doctor_email", "contacts", "E-mail referujícího lékaře", [], required=False,
          note="Požadováno formulářem MDT")

    # Diagnosis: confirmed histology wins over suspected referral diagnosis.
    dx_items = []
    for d in sorted(facts.get("diagnosis", []), key=lambda d: d["props"].get("status") != "confirmed"):
        p = d["props"]
        when = _fmt_date(d["sources"][0]["doc_date"]) if d["sources"] else ""
        if p.get("status") == "confirmed":
            extra = ", ".join(x for x in [f"MKN-O {p['morphology']}" if p.get("morphology") else ""] if x)
            dx_items.append(item(f"{p.get('name')} – histologicky ověřeno {when}{(' (' + extra + ')') if extra else ''}",
                                 d["sources"], status="confirmed"))
        else:
            dx_items.append(item(f"{p.get('icd10', '')} – {p.get('name')} (suspektní, {when})", d["sources"],
                                 status="suspected", icd10=p.get("icd10")))
    field("diagnosis", "clinical", "Diagnóza", dx_items)
    epis = sorted(facts.get("epikriza", []), key=lambda e: (e["props"].get("doc_type") != "referral",
                                                            -(e["sources"][0]["doc_date"].toordinal() if e["sources"] and e["sources"][0]["doc_date"] else 0)))
    field("epikriza", "clinical", "Epikríza (stručný souhrn nemoci)",
          [item(epis[0]["props"]["text"], epis[0]["sources"])] if epis else [])
    q = facts.get("mdt_question", [])
    field("mdt_question", "clinical", "Požadavek / otázka na MDT", [item(x["props"]["text"], x["sources"]) for x in q])

    field("comorbidities", "history", "Komorbidity (OA)",
          [item(c["props"]["name"] + (f" ({c['props']['icd10']})" if c["props"].get("icd10") else ""), c["sources"])
           for c in _merge_contained(sorted(facts.get("condition", []), key=lambda c: c["sources"][0]["doc_date"] or date.min))])
    field("medications", "history", "Léková anamnéza (FA)",
          [item(" ".join(x for x in [m["props"].get("name"), m["props"].get("dose"), m["props"].get("schedule")] if x),
                m["sources"]) for m in facts.get("medication", [])])
    field("allergies", "history", "Alergie (AA)", [item(a["props"]["text"], a["sources"]) for a in facts.get("allergy", [])])

    meas = facts.get("measurement", [])
    ps = [m for m in meas if m["props"].get("measure") == "performance_status"]
    field("performance_status", "status", "Stav výkonnosti (ECOG / Karnofsky)",
          [item(f"{m['props']['scale']} {m['props']['value']:g}", m["sources"]) for m in ps],
          note="Není uvedeno v dokumentaci – doplnit" if not ps else "")
    wh = []
    for kind, label in (("height", "Výška"), ("weight", "Hmotnost")):
        ms = sorted((m for m in meas if m["props"].get("measure") == kind), key=lambda m: m["props"].get("date") or date.min)
        if ms:
            last_m = ms[-1]
            trend = " → ".join(f"{m['props']['value']:g} ({_fmt_date(m['props'].get('date'))})" for m in ms) if len(ms) > 1 else ""
            wh.append(item(f"{label} {last_m['props']['value']:g} {last_m['props']['unit']} ({_fmt_date(last_m['props'].get('date'))})"
                           + (f"; vývoj: {trend}" if trend else ""), [s for m in ms for s in m["sources"]]))
    field("weight_height", "status", "Váha a výška", wh)
    field("symptoms", "status", "Symptomy a jejich počátek",
          [item(s["props"]["name"] + (f" – od: {s['props']['onset']}" if s["props"].get("onset") else ""), s["sources"])
           for s in facts.get("symptom", [])])

    exams = sorted((e for e in facts.get("exam", []) if e["props"].get("exam_type") != "lab"),
                   key=lambda e: e["props"].get("date") or date.min)
    field("exams", "results", "Provedená vyšetření",
          [item(f"{_fmt_date(e['props'].get('date'))} · {e['props'].get('place')} · {e['props'].get('label')}",
                e["sources"], date=e["props"].get("date"), place=e["props"].get("place"), type=e["props"].get("label"),
                result=e["props"].get("result_text"), conclusion=e["props"].get("conclusion"))
           for e in exams if e["props"].get("exam_type") != "histology"])
    labs = facts.get("lab", [])
    by_date: dict = {}
    for l in labs:
        by_date.setdefault(l["props"].get("date"), []).append(l)
    lab_items = []
    for d in sorted(by_date, key=lambda x: x or date.min):
        rows = by_date[d]
        abnormal = [l for l in rows if l["props"].get("flag") or l["props"].get("is_tumor_marker")]
        text = ", ".join(f"{l['props']['analyte']} {l['props']['value']} {l['props'].get('unit', '')}".strip()
                         + (f" {l['props']['flag']}" if l["props"].get("flag") else "") for l in abnormal)
        lab_items.append(item(f"{_fmt_date(d)}: {text or 'bez patologických hodnot'}", [s for l in rows[:1] for s in l["sources"]],
                              date=d, rows=[{k: l["props"].get(k) for k in ("analyte", "value", "unit", "ref", "flag",
                                                                           "is_tumor_marker", "panel")} for l in rows]))
    tm = [l for l in labs if l["props"].get("is_tumor_marker")]
    field("labs", "results", "Laboratorní výsledky vč. onkomarkerů (TM)", lab_items,
          note="" if tm else "Nádorové markery nejsou v dokumentaci")
    histo = [e for e in exams if e["props"].get("exam_type") == "histology"]
    field("histology", "results", "Histologie", [item(f"{_fmt_date(h['props'].get('date'))}: {h['props'].get('result_text')}",
                                                      h["sources"]) for h in histo], required=False,
          note="" if histo else "Histologie zatím není k dispozici")

    notes = facts.get("note", [])
    # social / family / work history repeat in every GP letter – keep only the most recent one per category
    latest: dict[str, dict] = {}
    for n in notes:
        cat = n["props"].get("category")
        if cat in ("social", "family_history", "work", "abusus"):
            d = n["sources"][0]["doc_date"] if n["sources"] else None
            if cat not in latest or (d and latest[cat]["sources"][0]["doc_date"] and d > latest[cat]["sources"][0]["doc_date"]):
                latest[cat] = n
    notes = [n for n in notes if n["props"].get("category") not in latest or latest[n["props"]["category"]] is n]
    order = ["warning", "consent", "wish", "psychosocial", "information", "social", "family_history", "work", "abusus", "other"]
    notes.sort(key=lambda n: order.index(n["props"].get("category")) if n["props"].get("category") in order else 99)
    field("notes", "other", "Jiná důležitá sdělení (vč. přání pacienta)",
          [item(f"{NOTE_LABELS.get(n['props'].get('category'), '')}: {n['props']['text']}", n["sources"]) for n in notes])

    # Apply doctor confirmations / edits and coordinator additions.
    by_key: dict[str, list[dict]] = {}
    for e in entries:
        by_key.setdefault(e["field_key"], []).append(e)
    for f in fields:
        es = by_key.get(f["key"], [])
        for e in es:
            if e["kind"] == "add":
                f["items"].append({"text": e["value"], "sources": [], "verified": True, "added_by": e["by"],
                                   "added_on": e["on"]})
            elif e["kind"] == "edit":
                f["items"] = [{"text": e["value"], "sources": [], "verified": True, "edited_by": e["by"], "edited_on": e["on"]}]
        confirms = [e for e in es if e["kind"] == "confirm"]
        f["confirmed"] = bool(confirms) and all(confirms[-1]["on"] >= x["on"] for x in es)
        f["confirmed_by"] = confirms[-1]["by"] if confirms else None
        f["status"] = ("missing" if not f["items"] else
                       "unverified" if any(not i.get("verified", True) for i in f["items"]) else "ok")
        f["text"] = "\n".join(i["text"] for i in f["items"])
        f["label_en"] = LABEL_EN.get(f["key"], f["label"])
        f["note_en"] = NOTE_EN.get(f["note"], f["note"])

    missing = [f for f in fields if f["status"] == "missing" and (f["required"] or f["note"])]
    return {
        "cutoff": cutoff,
        "sections": [{"key": k, "label": l, "label_en": en, "fields": [f for f in fields if f["section"] == k]}
                     for k, l, en in SECTIONS],
        "missing": [{"key": f["key"], "label": f["label"], "label_en": f["label_en"], "note": f["note"],
                     "note_en": f["note_en"], "required": f["required"]} for f in missing],
        "unverified": [{"key": f["key"], "label": f["label"], "label_en": f["label_en"]} for f in fields
                       if f["status"] == "unverified"],
        "confirmed_count": sum(1 for f in fields if f["confirmed"]),
        "field_count": len(fields),
    }


def as_text(h: dict) -> str:
    """Copy-able plain text of the whole handover."""
    out = []
    for s in h["sections"]:
        out.append(s["label"].upper())
        for f in s["fields"]:
            out.append(f"{f['label']}: {f['text'] or '— CHYBÍ —'}")
        out.append("")
    return "\n".join(out)
